"""Batch 1 — typography sweep + verified content fixes.

Rules: every replacement asserts its match count so a silent no-op is impossible.
Only explicitly audited items are touched. No file writes unless all assertions pass.
"""
import io, re, sys

BASE = '/home/user/S.A.1/wp-content/themes/sarzaminaryan-child/data/'
G = BASE + 'ready-guides.php'
A = BASE + 'ready-articles.php'

files = {G: io.open(G, encoding='utf-8').read(), A: io.open(A, encoding='utf-8').read()}
before = {k: len(v) for k, v in files.items()}
log = []


def sweep(name, pattern, repl, expect_min=1, files_sel=None, flags=0):
    """Regex sweep over selected files; returns total replacements."""
    sel = files_sel or list(files)
    total = 0
    for k in sel:
        txt = files[k]
        new, n = re.subn(pattern, repl, txt, flags=flags)
        if n:
            files[k] = new
        total += n
    if total < expect_min:
        print('!! %-46s expected >=%d got %d' % (name, expect_min, total))
    log.append((name, total))
    return total


def rep(name, old, new, count=1, files_sel=None):
    """Exact-string replacement with per-file count check."""
    sel = files_sel or list(files)
    total = 0
    for k in sel:
        n = files[k].count(old)
        if n:
            files[k] = files[k].replace(old, new)
            total += n
    if total != count:
        print('!! %-46s expected %d got %d :: %s' % (name, count, total, old[:60]))
        sys.exit(1)
    log.append((name, total))


