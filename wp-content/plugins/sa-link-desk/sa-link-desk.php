namespace SA\LinkDesk;

defined( 'ABSPATH' ) || exit;

function options() {
	return (array) get_option( 'sa_link_desk', array() );
}

function wiki( $host ) {
	return (bool) preg_match( '/(?:^|\.)wikipedia\.org$/iD', rtrim( $host, '.' ) );
}

// Accept only bare local geographic routes. Editorial deep links are intentional.
function geo_path( $href ) {
	if ( preg_match( '/[\\\\\s?#]/', $href ) ) {
		return '';
	}
	$parts = wp_parse_url( $href );
	$home  = wp_parse_url( home_url( '/' ) );
	if ( ! $parts || isset( $parts['user'] ) || isset( $parts['pass'] ) ) {
		return '';
	}
	if ( isset( $parts['scheme'] ) && ! in_array( strtolower( $parts['scheme'] ), array( 'http', 'https' ), true ) ) {
		return '';
	}
	if ( isset( $parts['host'] ) && ( strcasecmp( $parts['host'], $home['host'] ) || ( $parts['port'] ?? null ) !== ( $home['port'] ?? null ) ) ) {
		return '';
	}
	$path = $parts['path'] ?? '';
	$base = rtrim( $home['path'] ?? '', '/' );
	return preg_match( '~^' . preg_quote( $base, '~' ) . '(/(?:province|city)/[^/]+/?)$~D', $path, $m ) ? trailingslashit( $m[1] ) : '';
}

function repair_prose( $html ) {
	if ( empty( options()['geo'] ) || ! is_singular( array( 'province', 'city' ) ) || ! in_the_loop() || get_the_ID() !== get_queried_object_id() || is_feed() || is_preview() || is_admin() || ( defined( 'REST_REQUEST' ) && REST_REQUEST ) ) {
		return $html;
	}
	$tags = new \WP_HTML_Tag_Processor( $html );
	$seen = array( geo_path( get_permalink() ) => true );
	while ( $tags->next_tag( 'A' ) ) {
		$path = geo_path( (string) $tags->get_attribute( 'href' ) );
		if ( ! $path ) {
			continue;
		}
		$to = function_exists( 'sa_redirect_target_for_path' ) ? sa_redirect_target_for_path( $path ) : '';
		if ( $to && preg_match( '~^/(city|province)/([^/]+)/$~D', $to, $m ) ) {
			$post = get_page_by_path( $m[2], OBJECT, array( $m[1] ) );
			if ( $post && is_post_publicly_viewable( $post ) && ! $post->post_password && $to === geo_path( get_permalink( $post ) ) && ! sa_redirect_target_for_path( $to ) ) {
				$tags->set_attribute( 'href', get_permalink( $post ) );
				$path = $to;
			}
		}
		if ( isset( $seen[ $path ] ) ) {
			$tags->remove_attribute( 'href' );
		}
		$seen[ $path ] = true;
	}
	return $tags->get_updated_html();
}
add_filter( 'the_content', __NAMESPACE__ . '\\repair_prose', 98 );

function unlink_wiki( $html ) {
	$tags = new \WP_HTML_Tag_Processor( $html );
	while ( $tags->next_tag( 'A' ) ) {
		$href = trim( (string) $tags->get_attribute( 'href' ) );
		if ( preg_match( '~^(?:https?:)?//~i', $href ) && wiki( (string) wp_parse_url( $href, PHP_URL_HOST ) ) ) {
			$tags->remove_attribute( 'href' );
		}
	}
	return $tags->get_updated_html();
}
// Include citations generated by the template, not just saved post_content.
add_action( 'template_redirect', static function () {
	if ( ! empty( options()['wiki'] ) && is_singular() && ! is_feed() && ! is_preview() && ! is_embed() && ! is_trackback() && ! wp_is_json_request() && 'GET' === ( $_SERVER['REQUEST_METHOD'] ?? '' ) && 'publish' === get_post_status( get_queried_object_id() ) ) {
		ob_start( static function ( $html ) {
			return false !== stripos( $html, '</html>' ) ? unlink_wiki( $html ) : $html;
		} );
	}
}, 99 );

