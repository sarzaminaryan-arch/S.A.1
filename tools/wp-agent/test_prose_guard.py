#!/usr/bin/env python3
"""آزمون نگهبان نثر — فیکسچرها از خودِ سایت زنده گرفته شده‌اند (۲۰۲۶-۱۱-۲۳).

هر «باید بگیرد» این فایل، یک خطای واقعی است که روی sarzaminaryan.ir منتشر شد و از
دروازه‌های پیشین گذشت. هر «نباید بگیرد»، یک صفحهٔ سالم است؛ اگر نگهبان آن‌ها را هم
رد کند، ابزار بی‌فایده و آزاردهنده می‌شود.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import prose_guard as pg  # noqa: E402
import wp_agent as wa  # noqa: E402

DATA = HERE / "replace_src" / "data"


def kinds(result):
    return sorted({p.split(":")[0].split(" ")[0] for p in result["problems"]})


# ── ۱. باید بگیرد: جملهٔ تکراری (شوش، منتشرشده) ──────────────────────────────
dup = ("<p>کشاورزی شوش، آبی و دیم، با آب از سد شاوور و دز تغذیه می‌شود. "
       "نیشکر بیشتر در دهستانی که رود شاوور از آن می‌گذرد، کشاورزی می‌کند.</p>")
dup2 = ("<p>کشاورزی در شوش را زمینِ حاصلخیز و کانال‌های آبیاری تعیین می‌کند. "
        "نیشکر بیشتر در دهستانی که رود شاوور می‌گذرد و از سد شاوور آب می‌گیرد.</p>"
        "<p>کشاورزی شوش، آبی و دیم، با آب از سد شاوور و دز تغذیه می‌شود.</p>"
        "<p>نیشکر بیشتر در دهستانی که رود شاوور از آن می‌گذرد، کشاورزی می‌کند.</p>")
many = "<p>" + " ".join([
    "این شهر، مرکز صنعت نفت و کشاورزی و خدمات در خوزستان بوده و بخشی از فرهنگ بختیاری و عربی را در ذهن دارد.",
    "این شهرستان، مرکز صنعت نفت و کشاورزی و خدمات در خوزستان بوده و بخشی از فرهنگ بختیاری را در ذهن دارد.",
    "این موزه، آثار و اسنادی از صنعت نفت ایران را به نمایش می گذارد و بخشی از تاریخ این شهر را گردآورنده می کند.",
    "این موزه، آثار و اسنادی از صنعت نفت ایران را به نمایش می گذارد و بخشی از تاریخ شهر را گردآورنده می کند.",
    "این منطقه، به عنوان شریان آب و انرژی در جنوب خوزستان شناخته شده است.",
    "این شهرستان، به عنوان شریان آب و انرژی در جنوب خوزستان شناخته شده است.",
]) + "</p>"
result = pg.check(many + many)
assert result["metrics"]["near_dup_pairs"] >= 3, result
assert any("تکرار/نیمه‌تکرار" in p for p in result["problems"]), result

# ── ۲. باید بگیرد: الگوی ماشینی «در لالی، …» (منتشرشده) ──────────────────────
pattern = "<p>" + " ".join(
    f"در لالی، گروه {i} از مردم با دام و کشاورزی روزگار می‌گذرانند و بازار محلی دارند."
    for i in range(1, 9)
) + "</p>"
assert any("آغاز" in p for p in pg.check(pattern)["problems"]), pg.check(pattern)

# ── ۳. باید بگیرد: نویسهٔ غیرفارسی (شوشتر «ہ»، لالی «סבי») ─────────────────────
assert any("غیرفارسی" in p for p in pg.check("شوشتر را «شہر آبی جهان» می‌شناسند.")["problems"])
assert any("غیرفارسی" in p for p in pg.check("روستاهای סביبر پبده و آرپناه.")["problems"])
# «ئ» فارسی است و نباید پرچم شود.
assert pg.check("مسجدسلیمان و چایپاره و بوئین‌زهرا در ایران‌اند و مردمش فارسی می‌گویند.")["ok"]

# ── ۴. باید بگیرد: بازماندهٔ ماشینی (دشت آزادگان روی سایت) ────────────────────
assert any("رندرنشده" in p for p in pg.check("&#۸۲۲۰;\\` نمونهٔ بازمانده")["problems"])
assert any("مارک‌داون" in p for p in pg.check("این **متن** با ستاره آمده است.")["problems"])

# ── ۵. باید بگیرد: متن پیش‌نویس (دشت آزادگان روی سایت) ───────────────────────
for stub in ("این مقاله یک پیش‌نویس پژوهشی است.", "اعداد باید بررسی شوند.",
             "جاذبه‌ها در حال تکمیل است.", "تاریخ تأسیس نامشخص است."):
    assert any("پیش‌نویس" in p for p in pg.check(
        stub + " شهرستان دزفول در خوزستان است و مردمی دارد که فارسی می‌گویند.")["problems"]), stub

# ── ۶. باید بگیرد: جدول (قاعدهٔ مطلق v3) و نامک لاتین ─────────────────────────
assert any("جدول" in p for p in pg.check("<table><tr><td>الف</td></tr></table>")["problems"])
assert any("جدول" in p for p in pg.check("| فصل | هوا |\n| بهار | خوب |")["problems"])
assert any("نامک" in p for p in pg.check(
    "همسایه‌ها: haftkel - جنوب و ramshir - شرق و hamidiyeh - غرب شهر.")["problems"])

# ── ۷. نباید بگیرد: صفحه‌های سالمِ واقعی ──────────────────────────────────────
for slug in ("ahvaz", "hamidiyeh", "bavi", "omidiyeh", "shiraz", "tabriz", "isfahan"):
    path = DATA / f"{slug}.json"
    if not path.is_file():
        continue
    got = pg.check_file(path)
    assert got["ok"], (slug, got["problems"])


# ── ۸. گیت روی مسیر نوشتن: متن بد نباید به سایت برسد ────────────────────────
try:
    wa.check_banned("شهرستان شوشتر با نویسهٔ اردو: شہر آبی جهان.")
except Exception as exc:                       # AgentError
    assert "نگهبان نثر" in str(exc), exc
else:
    raise AssertionError("نگهبان نثر روی مسیر نوشتن اجرا نشد")

# متن سالم باید از همان گیت بگذرد (بی‌خطا).
wa.check_banned("شهرستان شوشتر در شمال خوزستان است و سازه‌های آبی‌اش ثبت جهانی شده‌اند.")

print("OK: prose guard —", json.dumps({"fixtures": 8}, ensure_ascii=False))
