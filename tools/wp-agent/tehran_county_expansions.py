def main() -> None:
    outbox_dirs = ["tools/wp-agent/outbox/20261117-replace-tehran"]
    for slug, exps in EXPANSIONS.items():
        p = DATA_DIR / f"{slug}.json"
        spec = json.loads(p.read_text(encoding="utf-8"))
        for sec, paras in exps.items():
            if sec == "modern":
                spec["modern"][0]["p"].extend(paras)
            else:
                spec[sec].extend(paras)
        p.write_text(json.dumps(spec, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        subprocess.run(
            [sys.executable, str(ROOT / "replace_src" / "county_page.py"), slug],
            check=True,
        )
        outbox_dirs.append(f"tools/wp-agent/outbox/20261117-replace-{slug}")

    subprocess.run(
        [sys.executable, str(ROOT / "replace_src" / "check_template.py"), *outbox_dirs],
        check=True,
    )
    print("ALL 6 TEHRAN-PROVINCE COUNTIES PASSED CHECK_TEMPLATE.")


if __name__ == "__main__":
    main()
