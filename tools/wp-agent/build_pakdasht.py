def clean(text: str) -> str:
    fixed, applied = fix_text(text)
    if applied:
        print(f"  fa_lint fix: {'; '.join(applied[:4])}")
    return fixed


def clean_spec(spec: dict) -> dict:
    spec["tagline"] = clean(spec["tagline"])
    for key in ("intro", "map", "history", "people", "economy", "stay", "food", "notables"):
        rows = []
        for row in spec.get(key, []):
            if isinstance(row, dict) and "p" in row:
                row = dict(row, p=clean(row["p"]))
            elif isinstance(row, str):
                row = clean(row)
            rows.append(row)
        if rows:
            spec[key] = rows
    for key in ("people_list", "economy_list", "stay_list", "food_list"):
        if spec.get(key):
            spec[key] = [clean(x) for x in spec[key]]
    spec["meta"] = {k: (v if k in SKIP_META else clean(v)) if isinstance(v, str) else v
                    for k, v in spec["meta"].items()}
    return spec


